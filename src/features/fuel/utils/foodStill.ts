const BROWSE: Record<string, StillKey> = {
  protein: 'chicken',
  carbs: 'rice',
  fats: 'avocado',
  fastfood: 'burger',
  drinks: 'water',
  veg: 'veg',
  fruit: 'fruit',
  dairy: 'milk',
  snacks: 'chips',
};

/** A photo of this food. A real product photo wins. The name decides the rest. */
export function foodStill(food: {
  image?: string;
  name: string;
  category?: string;
  browse?: string;
}): string {
  if (food.image) return food.image;
  const name = food.name.toLowerCase();
  for (const [rule, key] of RULES) {
    if (rule.test(name)) return STILL[key];
  }
  const group = food.browse || food.category;
  if (group && group in BROWSE) return STILL[BROWSE[group]];
  return STILL.chicken;
}
