import { ExerciseDefinition } from '../../types/workout';

function lift(
  partial: Omit<ExerciseDefinition, 'discipline' | 'defaultSets'> & {
    discipline?: ExerciseDefinition['discipline'];
    defaultSets?: number;
  }
): ExerciseDefinition {
  const { defaultSets = 3, restSecs = 90, ...rest } = partial;
  return {
    discipline: 'lift',
    defaultSets,
    restSecs,
    defaultRestSeconds: rest.defaultRestSeconds ?? restSecs,
    ...rest,
    mechanic: rest.mechanic || (rest.tier === 'Isolation Finish' ? 'isolation' : 'compound'),
    primaryMuscleGroup: rest.primaryMuscleGroup || rest.primaryMuscle,
  };
}

